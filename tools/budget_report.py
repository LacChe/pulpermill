"""Measures every prompt in tokens, for a sample, a medium and a very large story, and writes docs/prompts/samples/budget-report.md.
Run from the repository root: python tools/budget_report.py   (needs the Gemma tokenizer files, see pulpermill/prompts/tokens.py)."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests" / "prompts"))

import prompt_cases as cases                                                                         # noqa: E402
from pulpermill.prompts import budget                                                # noqa: E402
from pulpermill.prompts import textfiles as tx                                       # noqa: E402

TIER_TEXT = {"sample": "the Salt Coast sample (3 people)", "medium": "a medium story (5 people, 3 items a list, 8 chapters)",
             "large": "a very large story (8 people, 5 items in every list, 12 chapters, every text past its cap)"}


def squeeze_needed(tiername, name):
    """The first squeeze factor at which this prompt fits, or None."""
    for factor in budget.SQUEEZES:
        with tx.squeeze(factor):
            made = cases.tier(tiername)[name]
        if budget.measure(made).ok:
            return factor
    return None


def capacity_rows():
    """How big a cast fits, for the two largest prompts, with ordinary texts (a sentence or two) and with every text at its cap."""
    rows = []
    for chars, label in ((200, "ordinary texts"), (2400, "every text at its cap")):
        for n in (3, 4, 5, 6, 8):
            args = dict(cast=n, each=3 if chars < 1000 else cases.MAX_ITEMS, ties=2 * n, chapters=8, chars=chars)
            gen, plan = cases.inflate(cases.generate_request(), **args), cases.inflate(cases.plan_request(), **args)
            w = budget.measure(cases.P.writer_prompt(gen, cases.P.writer_plan(), 1, cases.prose(6500)))
            p = budget.measure(cases.P.planner_think_prompt(plan))
            rows.append(f"| {label} | {n} | {w.tokens} | {'fits' if w.ok else 'over'} | {p.tokens} | {'fits' if p.ok else 'over'} |")
    return rows


def main():
    b = budget.budgets()
    lines = [f"# Prompt token budgets (generated by tools/budget_report.py)", "",
             f"Context {b['n_ctx']} tokens, margin {b['margin']}. A prompt may use `n_ctx - reply room - margin`. "
             "Counted on the Gemma 3 tokenizer with the chat template around the prompt.", ""]
    for tiername in ("sample", "medium", "large"):
        prompts = cases.tier(tiername)
        lines += [f"## {TIER_TEXT[tiername]}", "", "| prompt | tokens | allowed | left | squeeze that fits |", "|---|---:|---:|---:|---|"]
        for name, prompt in prompts.items():
            m = budget.measure(prompt)
            need = "none needed" if m.ok else squeeze_needed(tiername, name)
            lines.append(f"| {name} | {m.tokens} | {m.limit} | {m.headroom} | {need if need is not None else 'does not fit'} |")
        lines.append("")
    lines += ["## How many people fit (no squeeze)", "",
              f"The writer's section 2 prompt allows {budget.input_limit('writer')} tokens, the planner's thinking prompt {budget.input_limit('planner_think')}.", "",
              "| texts | people | writer tokens | writer | planner tokens | planner |", "|---|---:|---:|---|---:|---|", *capacity_rows(), ""]
    out = ROOT / "docs" / "prompts" / "samples" / "budget-report.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
